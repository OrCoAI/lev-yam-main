export type EventsDict = Dict

/** DB constraint / error → the bilingual sentence the owner should read. */
export function friendlyError(et: Dict, err: unknown): string {
  const msg = err instanceof Error ? err.message : String((err as { message?: string })?.message ?? err)
  const map: [string, string][] = [
    ['events_public_optional_bilingual', et.errOptionalBilingual],
    ['events_public_bilingual', et.errBilingual],
    ['events_events_slug_uniq', et.errSlugTaken],
    ['events_slug_format', et.errSlugFormat],
    ['events_recurrence_valid', et.errRecurrence],
    ['events_image_paths_valid', et.errImage],
    ['upload_failed', et.errImage],
    ['translate_forbidden', et.errTranslateForbidden],
    ['events_public_reviewed_arabic', et.errReviewArabic],
    ['not_configured', et.errTranslateSetup],
    ['too_long', et.errTranslateLong],
    ['nothing_to_translate', et.errTranslateEmpty],
    ['translate_failed', et.errTranslate],
    ['unauthorized', et.errSession],
    ['forbidden', et.errNotWritten],
    ['not_written', et.errNotWritten],
  ]
  for (const [needle, text] of map) if (msg.includes(needle)) return text
  return msg
}
